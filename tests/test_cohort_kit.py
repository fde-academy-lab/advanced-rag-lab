def test_blueprint_counts_are_the_repository_counts():
    """Every number the blueprint quotes is recomputed here. Update the blueprint, not the test."""
    text = (SKILL / "references" / "blueprint.md").read_text()
    units = [p for p in (ROOT / "lab-simulator" / "units").iterdir() if p.is_dir()]
    drills = [p for p in units if re.match(r"^[A-Z]D\d", p.name)]
    facts = {
        "Units (25 to 45 minutes, three gates) | " + str(len(units) - len(drills)): True,
        "Drills (5 to 15 minutes, one idea) | " + str(len(drills)): True,
        f"| Workflows | {len(list((ROOT / '.github' / 'workflows').glob('*.yml')))} |": True,
        f"| Discussion forms | {len(list((ROOT / '.github' / 'DISCUSSION_TEMPLATE').glob('*.yml')))} |": True,
        f"{len(seed.CATEGORIES)} custom categories": True,
        f"{len(seed.LABELS) + len(seed.DISCUSSION_LABELS)} labels": True,
        f"{len(seed.MILESTONES)} milestones": True,
        f"{len(seed.ISSUES)} issues": True,
        f"{len(seed.DISCUSSIONS)} threads": True,
        f"the Lifecycle board ({len(seed.LIFECYCLE)} practices)": True,
        f"| Categories | {6 + len(seed.CATEGORIES)}:": True,
    }
    missing = [line for line in facts if line not in text]
    assert not missing, missing


PLACEHOLDER = re.compile(r"[A-Z]{2,}|NN|week-0W|<")
# Paths that exist only in a cohort repository, generated by the kit. Named in the blueprint as
# "new for a cohort"; they are allowed to be absent from the reference repository.
COHORT_ONLY = ("docs/11-cohort/", "scripts/seed/threads_cohort.py", "calendar/", "resources/")


def test_repository_paths_named_in_the_kit_exist():
    """A backticked path under a real top-level directory must exist. Placeholders are skipped."""
    roots = ("docs/", "scripts/", "lab-simulator/", "tests/", ".github/", "cohort-kit/",
             "notebooks/", "raglab/")
    bad = []
    for md in kit_markdown():
        for path in re.findall(r"`([^`\s]+)`", md.read_text()):
            if not path.startswith(roots) or PLACEHOLDER.search(path):
                continue
            if path.startswith(COHORT_ONLY):
                continue
            path = path.split("#")[0].rstrip("/")
            if "*" in path or path.endswith((".yml`", ")")):
                continue
            if not (ROOT / path).exists():
                bad.append(f"{md.relative_to(ROOT)}: {path}")
    assert not bad, bad


def test_claims_about_tests_point_at_tests_that_exist():
    """'tests/test_x.py enforces …' is only true if the file has a test about the subject."""
    subjects = {
        "test_workflows.py": ["secrets", "REQUIRED_CHECKS", "DISCUSSION_TEMPLATE"],
        "test_seed_content.py": ["100"],
        "test_measurements.py": ["RD2"],
    }
    for name, needles in subjects.items():
        src = (ROOT / "tests" / name).read_text()
        for needle in needles:
            assert needle in src, f"{name} is claimed to cover {needle!r} and does not"


