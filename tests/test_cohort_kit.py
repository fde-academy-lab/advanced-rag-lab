# ─────────────────────────────────────────────────────── unanswered_questions ──
def q(number, *, hours_old=48, answered=False, commenters=()):
    return Question(number=number, title=f"q{number}", url="u", author="learner",
                    created=NOW - dt.timedelta(hours=hours_old), answered=answered,
                    category="Q&A",
                    commenters=[(c, NOW - dt.timedelta(hours=1)) for c in commenters])


def test_instructors_are_the_maintain_and_admin_roles():
    assert instructors(EXAMPLE) == {"instructor-handle", "ta-handle"}


def test_overdue_is_unanswered_old_and_untouched_by_staff():
    staff = {"instructor-handle"}
    items = overdue([
        q(1),                                             # listed
        q(2, answered=True),                              # answered
        q(3, hours_old=3),                                # too new
        q(4, commenters=("Instructor-Handle",)),          # staff replied, case-insensitive
        q(5, commenters=("another-learner",)),            # a peer replied: still listed
        q(6, hours_old=200),                              # oldest first
    ], staff, NOW, hours=24)
    assert [i.number for i in items] == [6, 1, 5]


def test_render_is_instructor_facing_and_marks_itself():
    text = render(overdue([q(1)], set(), NOW), NOW, 24)
    assert text.startswith("<!-- cohort-kit:unanswered:v1 -->")
    assert "| 2.0d | Q&A | [q1](u) | @learner |" in text
    assert "mark the answer" in text
    assert "Nothing is waiting" in render([], NOW, 24)


